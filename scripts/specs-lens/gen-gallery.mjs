#!/usr/bin/env node
// Writes the four WS4 gallery scene documents into the Platform Lab as a Lens
// TypeScript module, so LEAF scenarios can present them on the scene
// controller.
//
//   node scripts/specs-lens/gen-gallery.mjs --viro <viro checkout> [--project <lens dir>]
//
// The documents are viro's __test__/fixtures/specs/gallery/*.scene.json,
// compiled from examples/specs-platform-lab/{SpecsPlatformLab,Placement,
// Interaction,Navigation}Scene.tsx. They are embedded as JSON strings and
// parsed on each call, so a scenario can change its copy freely.
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const repo = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const arg = (name, fallback) => {
  const i = process.argv.indexOf(name);
  return i >= 0 ? process.argv[i + 1] : fallback;
};
const viro = path.resolve(arg("--viro", repo));
const project = path.resolve(arg("--project", path.join(repo, "examples/specs-platform-lab/lens")));
const names = ["hello", "placement", "interaction", "navigation"];

const entries = names.map((name) => {
  const file = path.join(viro, "__test__/fixtures/specs/gallery", name + ".scene.json");
  const json = JSON.stringify(JSON.parse(readFileSync(file, "utf8")));
  return `  ${name}: ${JSON.stringify(json)},`;
});

const out = `// Generated by scripts/specs-lens/gen-gallery.mjs from viro
// __test__/fixtures/specs/gallery. Do not edit; regenerate instead.

/** The four WS4 gallery scenes. */
export type ViroLabGalleryScene = ${names.map((n) => JSON.stringify(n)).join(" | ")};

const SCENES: Record<ViroLabGalleryScene, string> = {
${entries.join("\n")}
};

/** A fresh copy of one gallery scene document (scene protocol 2). */
export function galleryScene(name: ViroLabGalleryScene): Record<string, unknown> & { nodes: Array<Record<string, unknown>> } {
  return JSON.parse(SCENES[name]);
}

/** Every image source the gallery scenes use, for the asset registry. */
export const GALLERY_IMAGE_SOURCES: readonly string[] = ${JSON.stringify(
  [...new Set(names.flatMap((n) => JSON.parse(readFileSync(path.join(viro, "__test__/fixtures/specs/gallery", n + ".scene.json"), "utf8")).nodes.filter((x) => x.kind === "image").map((x) => x.source)))]
)};
`;
const dir = path.join(project, "Assets/ViroSpecsLab/Gallery");
mkdirSync(dir, { recursive: true });
writeFileSync(path.join(dir, "ViroLabGallery.ts"), out);
console.log("Wrote", path.relative(repo, path.join(dir, "ViroLabGallery.ts")));
